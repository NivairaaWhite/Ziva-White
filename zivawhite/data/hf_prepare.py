# ------------------------------------------------------------------------------------ row sources
def read_local(path: str, text_col: str = "text") -> Iterator[Dict[str, Any]]:
    """Rows from a local .jsonl/.json file, a .txt file (one document), or a folder of them: for offline use and tests."""
    paths = ([os.path.join(path, n) for n in sorted(os.listdir(path))] if os.path.isdir(path) else [path])
    for p in paths:
        if p.endswith(".txt"):
            with open(p, encoding="utf-8") as f:
                yield {text_col: f.read()}
        elif p.endswith(".jsonl"):
            with open(p, encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        try:
                            yield json.loads(line)
                        except json.JSONDecodeError:
                            continue
        elif p.endswith(".json"):
            with open(p, encoding="utf-8") as f:
                data = json.load(f)
            yield from (data if isinstance(data, list) else [data])


def iter_rows(recipe: Recipe, local: Optional[str] = None, streaming: bool = True) -> Iterator[Dict[str, Any]]:
    if local:
        yield from read_local(local, recipe.column or "text")
        return
    try:
        from datasets import load_dataset
    except ImportError:
        raise SystemExit("downloading needs the `datasets` package: pip install datasets  (or use --local FILE)") from None
    if recipe.gated:
        print(f"[hf_prepare] NOTE: {recipe.hf_id} is gated: if loading fails, accept its terms on huggingface.co and run `huggingface-cli login`.")
    yield from load_dataset(recipe.hf_id, recipe.config, split=recipe.split, streaming=streaming)


# ----------------------------------------------------------------------------------- converters
def convert_text(row: Dict[str, Any], column: str) -> Optional[str]:
    t = row.get(column)
    return t if isinstance(t, str) and t.strip() else None


def convert_chat(row: Dict[str, Any], column: str) -> Optional[Dict[str, Any]]:
    msgs = normalize_conversation(row.get(column))
    return {"messages": msgs} if msgs else None


def convert_prefs(row: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    pair = normalize_preference(row)
    if pair is None:
        return None
    history, chosen, rejected = pair
    return {"prompt": history, "chosen": chosen, "rejected": rejected}


_GLAIVE_TURN = re.compile(r"(?m)^(USER|ASSISTANT|FUNCTION RESPONSE):\s*")


def _json_args(raw: str) -> Optional[Dict[str, Any]]:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] == "'":
        raw = raw[1:-1]
    try:
        obj = json.loads(raw)
    except json.JSONDecodeError:
        return None
    return obj if isinstance(obj, dict) else None


def convert_glaive(row: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """glaive-function-calling-v2: a `system` string (with the function specs) and a `chat` transcript of
    USER:/ASSISTANT:/FUNCTION RESPONSE: turns, where an assistant call looks like
    <functioncall> {"name": "...", "arguments": '{...}'}. Best effort: any call that does not parse drops the row."""
    system, chat = row.get("system"), row.get("chat")
    if not isinstance(system, str) or not isinstance(chat, str):
        return None
    system = re.sub(r"^\s*SYSTEM:\s*", "", system).strip()
    parts = _GLAIVE_TURN.split(chat.replace("<|endoftext|>", ""))
    msgs: List[Dict[str, str]] = [{"role": "system", "content": protocol_preamble() + "\n" + system}]
    for i in range(1, len(parts) - 1, 2):
        who, body = parts[i], parts[i + 1].strip()
        if not body:
            continue
        if who == "USER":
            msgs.append({"role": "user", "content": body})
        elif who == "FUNCTION RESPONSE":
            msgs.append({"role": "tool", "content": body})
        else:
            if "<functioncall>" in body:
                m = re.search(r'"name":\s*"([^"]+)"', body)
                a = re.search(r'"arguments":\s*(\'.*\'|\{.*\})\s*\}\s*$', body.split("<functioncall>", 1)[1].strip(), re.S)
                args = _json_args(a.group(1)) if a else None
                if not m or args is None:
                    return None
                body = format_tool_call(m.group(1), args)
            msgs.append({"role": "assistant", "content": body})
    msgs = normalize_conversation(msgs)
    if not msgs:
        return None
    # a function call must be followed by its result before the next assistant turn
    return {"messages": msgs}


def _load_json_field(value: Any) -> Any:
    if isinstance(value, str):
        try:
            return json.loads(value)
        except json.JSONDecodeError:
            return None
    return value


def convert_xlam(row: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """xlam-function-calling-60k: `query`, `tools` (JSON list of specs) and `answers` (JSON list of calls). Only
    single-call rows are kept (the protocol is one call per turn). Best effort."""
    query, tools, answers = row.get("query"), _load_json_field(row.get("tools")), _load_json_field(row.get("answers"))
    if not (isinstance(query, str) and query.strip() and isinstance(tools, list) and isinstance(answers, list) and len(answers) == 1):
        return None
    call = answers[0]
    if not (isinstance(call, dict) and isinstance(call.get("name"), str) and isinstance(call.get("arguments"), dict)):
        return None
    lines = []
    for t in tools:
        if not isinstance(t, dict) or not isinstance(t.get("name"), str):
            return None
        params = t.get("parameters") if isinstance(t.get("parameters"), dict) else {}
        args = ", ".join(f"{k}: {(v.get('description') or v.get('type') or '') if isinstance(v, dict) else v}" for k, v in params.items())
        lines.append(f"- {t['name']}({args}): {t.get('description', '')}")
    system = protocol_preamble() + "\nTools:\n" + "\n".join(lines)
    return {"messages": [{"role": "system", "content": system}, {"role": "user", "content": query.strip()},
                         {"role": "assistant", "content": format_tool_call(call["name"], call["arguments"])}]}


def convert(recipe_kind: str, row: Dict[str, Any], column: str = "") -> Any:
    if recipe_kind == "text":
        return convert_text(row, column)
    if recipe_kind == "chat":
        return convert_chat(row, column)
    if recipe_kind == "prefs":
        return convert_prefs(row)
    if recipe_kind == "glaive":
        return convert_glaive(row)
    if recipe_kind == "xlam":
        return convert_xlam(row)
    raise ValueError(f"unknown kind {recipe_kind!r}")


# ---------------------------------------------------------------------------------------- writers
def write_provenance(out_path: str, recipe: Optional[Recipe], extra: Dict[str, Any]) -> str:
    info = {"created": time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime()),
            "source": asdict(recipe) if recipe else None, **extra,
            "reminder": "The license here is what the dataset card stated when this tool was written (or 'not verified'). "
                        "Confirm it, and the terms of any model that generated the data, before publishing a trained model."}
    path = out_path.rstrip("/\\") + ".provenance.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(info, f, indent=2, ensure_ascii=False)
    return path


def write_jsonl(out_path: str, rows: Iterable[Dict[str, Any]], kind: str, column: str = "", max_rows: Optional[int] = None,
                min_ok_fraction: float = 0.5, recipe: Optional[Recipe] = None) -> Dict[str, Any]:
    """Convert and write rows. Written to a temp file and renamed only if the conversion looks right: when most rows
    fail to parse (a schema I guessed wrong), nothing is left behind and the error says what to do."""
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    tmp = out_path + ".tmp"
    seen = kept = 0
    with open(tmp, "w", encoding="utf-8") as f:
        for row in rows:
            seen += 1
            out = convert(kind, row, column)
            if out is not None:
                f.write(json.dumps(out, ensure_ascii=False) + "\n")
                kept += 1
                if max_rows and kept >= max_rows:
                    break
    if seen >= 20 and kept / seen < min_ok_fraction:
        os.remove(tmp)
        raise SystemExit(f"only {kept} of {seen} rows could be converted (<{min_ok_fraction:.0%}): the dataset's columns are "
                         f"probably not what this converter expects. Run `inspect` to see them, then adapt "
                         f"convert_{kind}() in zivawhite/data/hf_prepare.py. Nothing was written.")
    if kept == 0:
        os.remove(tmp)
        raise SystemExit(f"0 usable rows out of {seen}. Nothing was written.")
    os.replace(tmp, out_path)
    prov = write_provenance(out_path, recipe, {"kind": kind, "rows_seen": seen, "rows_kept": kept})
    return {"seen": seen, "kept": kept, "path": out_path, "provenance": prov}


def is_val_doc(index: int, val_permille: int, seed: int = 1337) -> bool:
    """Deterministic whole-document validation membership (~val_permille / 1000 of documents)."""
    return zlib.crc32(f"{seed}:{index}".encode()) % 1000 < val_permille


def write_text_shards(out_dir: str, docs: Iterable[str], tok, *, val_permille: int = 5, max_tokens: Optional[int] = None,
                      batch_docs: int = 256, seed: int = 1337, recipe: Optional[Recipe] = None) -> Dict[str, Any]:
    """Stream documents through the tokenizer straight into train.bin / val.bin (uint16, <eos> after each document).
    Memory stays flat however large the corpus is. Validation is a deterministic ~val_permille/1000 of WHOLE documents."""
    import numpy as np

    if tok.vocab_size > 65536:
        raise ValueError(f"vocab_size {tok.vocab_size} does not fit the uint16 shard format")
    os.makedirs(out_dir, exist_ok=True)
    n_train = n_val = n_docs = 0
    buf: List[tuple] = []

    def flush(ft, fv) -> None:
        nonlocal n_train, n_val
        ids_list = tok.encode_batch([t for _, t in buf], add_eos=True)
        for (idx, _), ids in zip(buf, ids_list):
            arr = np.asarray(ids, dtype=np.uint16)
            if is_val_doc(idx, val_permille, seed):
                arr.tofile(fv)
                n_val += len(arr)
            else:
                arr.tofile(ft)
                n_train += len(arr)
        buf.clear()

    with open(os.path.join(out_dir, "train.bin"), "wb") as ft, open(os.path.join(out_dir, "val.bin"), "wb") as fv:
        for doc in docs:
            buf.append((n_docs, doc))
            n_docs += 1
            if len(buf) >= batch_docs:
                flush(ft, fv)
                if max_tokens and n_train + n_val >= max_tokens:
                    break
        if buf and not (max_tokens and n_train + n_val >= max_tokens):
            flush(ft, fv)
    if n_train == 0:
        raise SystemExit("no training tokens were written (empty dataset?)")
    prov = write_provenance(os.path.join(out_dir, "shards"), recipe, {"kind": "text", "documents": n_docs,
                                                                      "train_tokens": n_train, "val_tokens": n_val})
    return {"documents": n_docs, "train_tokens": n_train, "val_tokens": n_val, "provenance": prov}


def text_docs(rows: Iterable[Dict[str, Any]], column: str, limit: Optional[int] = None) -> Iterator[str]:
    n = 0
    for row in rows:
        t = convert_text(row, column)
        if t is not None:
            yield t
            n += 1
            if limit and n >= limit:
                return


# --------------------------------------------------------------------------------------- the CLI
def _show(value: Any, width: int = 160) -> str:
    s = json.dumps(value, ensure_ascii=False, default=str) if not isinstance(value, str) else value
    return s if len(s) <= width else s[:width] + f"... [{len(s)} chars]"


def inspect_rows(rows: Iterable[Dict[str, Any]], n: int = 2) -> str:
    out = []
    for i, row in enumerate(rows):
        if i >= n:
            break
        out.append(f"--- row {i} ---")
        out += [f"{k}: {_show(v)}" for k, v in row.items()] if isinstance(row, dict) else [_show(row)]
    return "\n".join(out) if out else "(no rows)"


def _resolve(args) -> Recipe:
    if args.recipe:
        if args.recipe not in RECIPES:
            raise SystemExit(f"unknown recipe {args.recipe!r}; try: {', '.join(RECIPES)}")
        r = RECIPES[args.recipe]
    else:
        if not (args.hf_id and args.kind):
            raise SystemExit("give --recipe NAME, or --hf_id and --kind (and --column)")
        r = Recipe("custom", args.hf_id, args.kind, config=args.config, split=args.split, column=args.column)
    return r


def _limit(text: Optional[str]) -> Optional[int]:
    from ..plan import parse_count

    return int(parse_count(text)) if text else None


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Prepare Hugging Face datasets for ZivaWhite")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p, kinds=None):
        p.add_argument("--recipe", default=None, help=f"one of: {', '.join(RECIPES)}")
        p.add_argument("--hf_id"), p.add_argument("--kind", choices=["text", "chat", "prefs", "glaive", "xlam"])
        p.add_argument("--config", default=None), p.add_argument("--split", default="train")
        p.add_argument("--column", default="", help="text column / messages column (recipes set this)")
        p.add_argument("--local", default=None, help="read this local .jsonl/.json/.txt (or folder) instead of downloading")

    sub.add_parser("list")
    p = sub.add_parser("inspect"); common(p); p.add_argument("--rows", type=int, default=2)
    p = sub.add_parser("chat"); common(p); p.add_argument("--out", required=True); p.add_argument("--max_rows", default=None)
    p = sub.add_parser("prefs"); common(p); p.add_argument("--out", required=True); p.add_argument("--max_rows", default=None)
    p = sub.add_parser("text"); common(p); p.add_argument("--out_dir", required=True); p.add_argument("--tokenizer_dir", default=None)
    p.add_argument("--max_tokens", default=None, help="e.g. 2b"); p.add_argument("--val_permille", type=int, default=5)
    p = sub.add_parser("tokenizer"); common(p); p.add_argument("--out", required=True); p.add_argument("--vocab_size", type=int, default=32000)
    p.add_argument("--max_docs", default="200k"); p.add_argument("--extra_special", nargs="*", default=[])
    a = ap.parse_args(argv)

    if a.cmd == "list":
        for r in RECIPES.values():
            print(f"{r.key:26s} {r.kind:7s} {r.hf_id}" + (f" [{r.config}]" if r.config else ""))
            print(f"{'':26s} license: {r.license}{'' if r.license_checked else '  (not verified)'}" + ("  | GATED" if r.gated else ""))
            if r.caveats:
                print(f"{'':26s} {r.caveats}")
        return
    r = _resolve(a)
    col = a.column or r.column
    if a.cmd == "inspect":
        print(f"{r.hf_id} {r.config or ''} (kind={r.kind}, license: {r.license})")
        print(inspect_rows(iter_rows(r, a.local), a.rows))
        return
    want = {"chat": ("chat", "glaive", "xlam"), "prefs": ("prefs",), "text": ("text",), "tokenizer": ("text",)}[a.cmd]
    if r.kind not in want:
        raise SystemExit(f"recipe {r.key!r} is kind {r.kind!r}, which `{a.cmd}` cannot produce")
    print(f"[hf_prepare] {r.hf_id}: license {r.license}{'' if r.license_checked else ' (NOT verified)'}")
    if r.caveats:
        print(f"[hf_prepare] note: {r.caveats}")
    if a.cmd in ("chat", "prefs"):
        res = write_jsonl(a.out, iter_rows(r, a.local), r.kind, col, _limit(a.max_rows), recipe=r)
        print(f"[hf_prepare] kept {res['kept']:,} of {res['seen']:,} rows -> {res['path']} (+ {os.path.basename(res['provenance'])})")
    elif a.cmd == "text":
        from ..tokenizer import load_tokenizer

        tok = load_tokenizer(a.tokenizer_dir)
        res = write_text_shards(a.out_dir, text_docs(iter_rows(r, a.local), col), tok, val_permille=a.val_permille,
                                max_tokens=_limit(a.max_tokens), recipe=r)
        print(f"[hf_prepare] {res['documents']:,} documents -> {res['train_tokens']:,} train / {res['val_tokens']:,} val tokens in {a.out_dir}")
    else:
        from ..tokenizer import BPETokenizer

        docs = text_docs(iter_rows(r, a.local), col, limit=_limit(a.max_docs))
        tok = BPETokenizer.train_from_iterator(docs, a.vocab_size, a.out, extra_special=a.extra_special)
        write_provenance(a.out, r, {"kind": "tokenizer", "vocab_size": tok.vocab_size, "max_docs": a.max_docs})
        print(f"[hf_prepare] trained a {tok.vocab_size:,}-token BPE -> {a.out}  (use it as --tokenizer_dir everywhere)")


if __name__ == "__main__":
    main()
