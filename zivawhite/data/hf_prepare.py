"""
hf_prepare.py - turn public Hugging Face datasets into ZivaWhite training data.

    pip install datasets                                   # only needed for downloading, not for training
    python -m zivawhite.data.hf_prepare list               # the built-in recipes and what is known about each
    python -m zivawhite.data.hf_prepare inspect --recipe smoltalk              # look at the real columns first
    python -m zivawhite.data.hf_prepare tokenizer --recipe fineweb --max_docs 300000 --vocab_size 32000 --out tokenizers/gen32k
    python -m zivawhite.data.hf_prepare text  --recipe fineweb --tokenizer_dir tokenizers/gen32k --out_dir data/processed --max_tokens 2b
    python -m zivawhite.data.hf_prepare chat  --recipe smol-smoltalk --out data/chat/smol.jsonl --max_rows 100000
    python -m zivawhite.data.hf_prepare prefs --recipe ultrafeedback --out data/prefs/uf.jsonl --max_rows 20000
    python -m zivawhite.data.hf_prepare chat  --recipe glaive-function-calling --out data/chat/tools.jsonl

What each output feeds:
    text   -> train.bin / val.bin shards (uint16, <eos> after every document), for `python -m zivawhite.train`
    chat   -> {"messages": [...]} JSONL, for `python -m zivawhite.sft`      (system/user/assistant/tool roles kept)
    prefs  -> {"prompt", "chosen", "rejected"} JSONL, for `python -m zivawhite.dpo`
    tokenizer -> a byte-level BPE trained on a sample of the text, for ALL of the above

Three honesty rules baked in:
  * `inspect` shows real rows before you commit to a conversion. Recipes for schemas I could not check against the
    live data (Glaive, xLAM) are best-effort: they refuse to write a file if most rows fail to parse, instead of
    quietly producing an empty dataset.
  * Every output gets a `<output>.provenance.json` (source, config, row counts, the license as stated, caveats).
    Hand it to `export --data_note @file` so your model card says what the model was trained on.
  * A dataset's own license is not the only constraint. Several of these were GENERATED by commercial models
    (SmolTalk is tagged "Synthetic"; OpenHermes-2.5, UltraFeedback's completions and others include outputs of
    proprietary LLMs), and those providers' terms may restrict how the outputs can be used. Read each dataset card
    and the terms of the generating models before you publish a model trained on them. This tool records; it
    cannot decide that for you.
"""
