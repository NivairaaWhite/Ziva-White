"""
export_hf.py - turn a ZivaGPT checkpoint into a standard Hugging Face model folder.

    python -m zivawhite.export_hf --checkpoint runs/ziva/checkpoint.pt --out exports/ziva-white-25m \\
        --name Ziva-White-25M --license apache-2.0 --verify
    python -m zivawhite.app export ...                                  # same thing

What you get in --out (this folder, and ONLY this folder, is what you publish):

    model.safetensors          weights, no pickle, as a LlamaForCausalLM (see hf_compat.py for why that is exact)
    config.json                the architecture (hidden size, heads, KV heads, rope, ...)
    generation_config.json     sensible sampling defaults for transformers / vLLM
    tokenizer.json + tokenizer_config.json + special_tokens_map.json   incl. the chat template
    README.md                  an honest model card filled in from the checkpoint
    Modelfile                  for `ollama create` (Ollama imports Llama-architecture safetensors folders)

It loads with no custom code:

    from transformers import AutoModelForCausalLM, AutoTokenizer
    model = AutoModelForCausalLM.from_pretrained("exports/ziva-white-25m")

Pass --verify (needs torch + transformers) to load the folder back and prove it produces the same
logits as the original checkpoint. Pass --push user/repo to upload it (private unless --public).
Do NOT upload the training run folder instead: it holds optimizer state and pickle checkpoints.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import time
from typing import Any, Dict, Optional

from .chat import ASSISTANT_TAG, HF_CHAT_TEMPLATE, SYSTEM_TAG, TOOL_TAG, USER_TAG
from .hf_compat import hf_config_dict, zivagpt_to_hf_state
from .modelconfig import ModelConfig

DTYPES = ("float32", "float16", "bfloat16")


# ------------------------------------------------------------------------- pure text outputs
def build_text_files(cfg: ModelConfig, *, bos_id: Optional[int], eos_id: Optional[int], pad_id: Optional[int],
                     dtype: str, name: str, license_id: Optional[str], data_note: Optional[str],
                     ckpt_meta: Dict[str, Any], bos_token: str = "<bos>", eos_token: str = "<eos>",
                     pad_token: str = "<pad>", unk_token: str = "<unk>") -> Dict[str, str]:
    """Everything in the export folder except weights and tokenizer.json, as {filename: text}."""
    hf_cfg = hf_config_dict(cfg, bos_id=bos_id, eos_id=eos_id, pad_id=pad_id, dtype=dtype)
    chat = bool(ckpt_meta.get("behavior_tuned"))
    gen_cfg = {
        "_from_model_config": True, "bos_token_id": bos_id, "eos_token_id": eos_id, "pad_token_id": pad_id,
        "do_sample": True, "temperature": 0.7, "top_p": 0.9, "top_k": 50, "repetition_penalty": 1.1,
        "max_new_tokens": min(512, cfg.block_size // 2),
    }
    tok_cfg = {
        "tokenizer_class": "PreTrainedTokenizerFast", "model_max_length": cfg.block_size,
        "bos_token": bos_token, "eos_token": eos_token, "pad_token": pad_token, "unk_token": unk_token,
        "clean_up_tokenization_spaces": False, "add_bos_token": False,
        "chat_template": HF_CHAT_TEMPLATE,
    }
    special = {"bos_token": bos_token, "eos_token": eos_token, "pad_token": pad_token, "unk_token": unk_token}
    return {
        "config.json": json.dumps(hf_cfg, indent=2),
        "generation_config.json": json.dumps(gen_cfg, indent=2),
        "tokenizer_config.json": json.dumps(tok_cfg, indent=2),
        "special_tokens_map.json": json.dumps(special, indent=2),
        "Modelfile": build_modelfile(cfg, chat=chat),
        "README.md": build_model_card(cfg, name=name, license_id=license_id, data_note=data_note,
                                      ckpt_meta=ckpt_meta, dtype=dtype),
    }


def build_modelfile(cfg: ModelConfig, chat: bool = True) -> str:
    """An Ollama Modelfile. `FROM .` imports this safetensors folder (Ollama supports Llama-architecture
    safetensors); to go through GGUF instead, convert with llama.cpp and point FROM at the .gguf file.
    The TEMPLATE reproduces chat.py's prompt format exactly (<|role|>\\ncontent\\n per message, then an open
    <|assistant|>). Written from Ollama's documented Modelfile syntax and NOT run against Ollama here:
    `ollama run` it once and compare a reply with `python -m zivawhite.app ask`."""
    stops = "\n".join(f'PARAMETER stop "{t}"' for t in (USER_TAG, ASSISTANT_TAG, SYSTEM_TAG, TOOL_TAG))
    template = ('TEMPLATE """{{- range .Messages }}<|{{ .Role }}|>\n{{ .Content }}\n{{ end }}<|assistant|>\n"""'
                if chat else '')
    note = ("" if chat else "# NOTE: this checkpoint is a BASE model (text completion), not chat-tuned: it will "
                            "continue text rather than answer. Fine-tune it with `app.py sft` first.\n")
    return (f"# Ollama Modelfile generated by zivawhite.export_hf\n{note}"
            f"FROM .\n{template}\n{stops}\n"
            f"PARAMETER temperature 0.7\nPARAMETER top_p 0.9\nPARAMETER repeat_penalty 1.1\n"
            f"PARAMETER num_ctx {cfg.block_size}\n")


def build_model_card(cfg: ModelConfig, *, name: str, license_id: Optional[str], data_note: Optional[str],
                     ckpt_meta: Dict[str, Any], dtype: str) -> str:
    params_m = cfg.total_params() / 1e6
    chat = bool(ckpt_meta.get("behavior_tuned"))
    step, val = ckpt_meta.get("step"), ckpt_meta.get("val_loss")
    front = ["---", "library_name: transformers", "pipeline_tag: text-generation", "tags:", "- llama", "- text-generation",
             "- from-scratch", "- zivawhite"]
    if license_id:
        front.insert(1, f"license: {license_id}")
    front.append("---")
    kind = ("an instruction/chat-tuned model" if chat else
            "a BASE language model: it continues text, it does not follow instructions")
    data = data_note.strip() if data_note else (
        "**TODO before publishing:** describe the training data here: where it came from, how it was "
        "filtered, and under which license(s) you are allowed to use and redistribute models trained on it. "
        "Data produced by another AI model can carry that provider's terms of use, so check them.")
    lic = f"`{license_id}`" if license_id else "**not set** (add one before publishing, and make sure it is compatible with your training data's terms)"
    saved = time.strftime("%Y-%m-%d", time.gmtime())
    val_line = (f"- Validation loss at export: {val:.3f} (perplexity {math.exp(min(val, 20)):.1f})\n"
                if isinstance(val, (int, float)) else "")
    step_line = f"- Training steps: {step:,}\n" if isinstance(step, int) else ""
    # (kept out of the f-string below: nested quotes inside f-string expressions need Python 3.12)
    if chat:
        usage_prompt = "messages = [{'role': 'user', 'content': 'Hello!'}]"
        usage_ids = "ids = tok.apply_chat_template(messages, add_generation_prompt=True, return_tensors='pt')"
    else:
        usage_prompt = "prompt = 'The history of'"
        usage_ids = "ids = tok(prompt, return_tensors='pt').input_ids"
    return "\n".join(front) + f"""

# {name}

{name} is {kind}, trained from scratch with ZivaWhite (a small Llama-architecture
transformer: RMSNorm, rotary embeddings, SwiGLU, grouped-query attention, tied embeddings). Exported {saved}.

## Architecture

| | |
|---|---|
| Parameters | {params_m:,.1f}M ({cfg.count_params() / 1e6:,.1f}M excluding the embedding) |
| Layers / hidden size | {cfg.n_layer} / {cfg.n_embd} |
| Attention heads / KV heads | {cfg.n_head} / {cfg.kv_heads} (head size {cfg.head_dim}) |
| MLP width (SwiGLU) | {cfg.mlp_hidden} |
| Context length | {cfg.block_size} tokens |
| Vocabulary | {cfg.vocab_size:,} (byte-level BPE) |
| Weights stored as | {dtype} (safetensors) |

{step_line}{val_line}
## Usage

```python
from transformers import AutoModelForCausalLM, AutoTokenizer
tok = AutoTokenizer.from_pretrained("REPO_ID")
model = AutoModelForCausalLM.from_pretrained("REPO_ID")
{usage_prompt}
{usage_ids}
out = model.generate(ids, max_new_tokens=128, do_sample=True, temperature=0.7, repetition_penalty=1.1)
print(tok.decode(out[0][ids.shape[1]:], skip_special_tokens=True))
```

Also usable with vLLM (it is a standard `LlamaForCausalLM`) and, via the included `Modelfile`, Ollama.
Chat format: `<|system|>`, `<|user|>`, `<|assistant|>`, `<|tool|>` turns, each `<|role|>\\ncontent\\n` (see `chat_template`).

## Training data

{data}

## Intended use and limitations

- A small model trained on a limited corpus: expect fluent-sounding text that is often **wrong**. Do not rely
  on it for facts, medical, legal, financial or safety-critical decisions.
- It has had little or no safety/alignment training; it can produce biased, false or inappropriate text.
- Quality is bounded by model size and training tokens, not by this packaging. Compare against its
  validation loss above, not against much larger models.

## License

{lic}
"""


# -------------------------------------------------------------------------------- the export
def export_hf(checkpoint: str, out_dir: str, *, tokenizer_dir: Optional[str] = None, dtype: str = "float16",
              name: str = "Ziva-White", license_id: Optional[str] = None, data_note: Optional[str] = None,
              prefer_best: bool = True, verify: bool = False) -> Dict[str, Any]:
    if dtype not in DTYPES:
        raise ValueError(f"dtype must be one of {DTYPES}")
    import torch
    from safetensors.torch import save_file

    from .checkpoint import load_checkpoint, resolve_serving_checkpoint
    from .tokenizer import BPETokenizer, tokenizer_or_exit

    src = resolve_serving_checkpoint(checkpoint) if prefer_best else checkpoint
    ckpt = load_checkpoint(src)
    cfg = ModelConfig.from_dict(ckpt["config"])
    extra = ckpt.get("extra") or {}
    meta = {"behavior_tuned": bool(extra.get("behavior_tuned")), "step": ckpt.get("step"), "val_loss": extra.get("val_loss")}

    tok = tokenizer_or_exit(src, ckpt, tokenizer_dir)
    if tok.vocab_size != cfg.vocab_size:
        raise SystemExit(f"checkpoint vocab_size={cfg.vocab_size} but the tokenizer has {tok.vocab_size}: "
                         f"pass the --tokenizer_dir this checkpoint was trained with")
    os.makedirs(out_dir, exist_ok=True)

    # 1. weights -> Llama names/layout, cast, written as safetensors with the metadata transformers requires
    target = getattr(torch, dtype)
    hf_state = zivagpt_to_hf_state({k: v for k, v in ckpt["model_state"].items() if k != "head.weight"}, cfg)
    tensors = {k: v.detach().to(target).contiguous().clone() for k, v in hf_state.items()}
    save_file(tensors, os.path.join(out_dir, "model.safetensors"), metadata={"format": "pt"})

    # 2. text files
    tok_info = dict(bos_id=getattr(tok, "bos_id", None), eos_id=getattr(tok, "eos_id", None), pad_id=getattr(tok, "pad_id", None))
    files = build_text_files(cfg, dtype=dtype, name=name, license_id=license_id, data_note=data_note,
                             ckpt_meta=meta, **tok_info)
    for fname, text in files.items():
        with open(os.path.join(out_dir, fname), "w", encoding="utf-8") as f:
            f.write(text)

    # 3. tokenizer.json (a self-contained HF tokenizer) -- the byte-level BPE this model was trained with
    if isinstance(tok, BPETokenizer):
        tok.save_hf_json(os.path.join(out_dir, "tokenizer.json"))
    else:
        raise SystemExit(f"{type(tok).__name__} cannot be exported yet: only a ZivaWhite byte-level BPE tokenizer "
                         f"(vocab.json + merges.txt) can. If you see this for the built-in byte tokenizer, "
                         f"`pip install tokenizers` and retrain with a BPE tokenizer.")

    result = {"out_dir": out_dir, "params": cfg.total_params(), "dtype": dtype, "files": sorted(os.listdir(out_dir)),
              "source_checkpoint": src}
    if verify:
        result["verify"] = verify_export(out_dir, ckpt, cfg, dtype)
    return result


def verify_export(out_dir: str, ckpt: Dict[str, Any], cfg: ModelConfig, dtype: str, tol: float = 2e-3) -> Dict[str, Any]:
    """Load the exported folder with transformers and compare its logits with ZivaGPT's on the same token ids
    (weights rounded to the export dtype first, so the comparison is about the MAPPING, not about rounding)."""
    import torch
    from transformers import AutoModelForCausalLM

    from .model import ZivaGPT

    target = getattr(torch, dtype)
    ziva = ZivaGPT(cfg)
    ziva.load_state_dict(ckpt["model_state"])
    ziva = ziva.to(target).float().eval()
    hf = AutoModelForCausalLM.from_pretrained(out_dir, torch_dtype=torch.float32).eval()
    g = torch.Generator().manual_seed(0)
    ids = torch.randint(0, cfg.vocab_size, (2, min(48, cfg.block_size)), generator=g)
    with torch.no_grad():
        ours = ziva.hidden_logits(ids)
        theirs = hf(ids).logits
    max_diff = float((ours - theirs).abs().max())
    scale = float(ours.abs().max())
    ok = max_diff <= tol * max(1.0, scale)
    report = {"max_abs_diff": max_diff, "logit_scale": scale, "ok": ok,
              "argmax_agreement": float((ours.argmax(-1) == theirs.argmax(-1)).float().mean())}
    if not ok:
        raise SystemExit(f"EXPORT VERIFICATION FAILED: {report}. Do not publish this folder.")
    return report


def push_to_hub(folder: str, repo_id: str, private: bool = True, token: Optional[str] = None,
                commit_message: str = "Upload model") -> str:
    """Upload the export folder. Private by default (flip it public on the website once you are happy).
    The token comes from `token` or the HF_TOKEN environment variable / `huggingface-cli login`."""
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    api.create_repo(repo_id=repo_id, repo_type="model", private=private, exist_ok=True)
    api.upload_folder(folder_path=folder, repo_id=repo_id, repo_type="model", commit_message=commit_message)
    return f"https://huggingface.co/{repo_id}"


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description="Export a ZivaGPT checkpoint as a Hugging Face LlamaForCausalLM folder")
    p.add_argument("--checkpoint", required=True, help="checkpoint.pt (the best snapshot beside it is used unless --last)")
    p.add_argument("--out", required=True)
    p.add_argument("--tokenizer_dir", default=None)
    p.add_argument("--dtype", default="float16", choices=DTYPES)
    p.add_argument("--name", default="Ziva-White")
    p.add_argument("--license", dest="license_id", default=None, help="SPDX-style id for the model card, e.g. apache-2.0 (left unset if omitted)")
    p.add_argument("--data_note", default=None, help="text (or @file) describing the training data and its licenses, for the card")
    p.add_argument("--last", action="store_true", help="export the rolling checkpoint instead of checkpoint_best.pt")
    p.add_argument("--verify", action="store_true", help="reload with transformers and compare logits (needs transformers)")
    p.add_argument("--push", default=None, metavar="USER/REPO", help="upload the folder to the Hugging Face Hub")
    p.add_argument("--public", action="store_true", help="with --push: make the repo public (default private)")
    a = p.parse_args(argv)
    note = a.data_note
    if note and note.startswith("@"):
        with open(note[1:], encoding="utf-8") as f:
            note = f.read()
    res = export_hf(a.checkpoint, a.out, tokenizer_dir=a.tokenizer_dir, dtype=a.dtype, name=a.name,
                    license_id=a.license_id, data_note=note, prefer_best=not a.last, verify=a.verify)
    print(f"exported {res['params'] / 1e6:.1f}M parameters ({res['dtype']}) from {res['source_checkpoint']} -> {a.out}")
    print("files:", ", ".join(res["files"]))
    if "verify" in res:
        print("verified against the original checkpoint:", res["verify"])
    if a.push:
        print("uploaded:", push_to_hub(a.out, a.push, private=not a.public))
    else:
        print("next: review README.md (training data + license), then --push USER/REPO, or see docs/PUBLISHING.md")


if __name__ == "__main__":
    main()
